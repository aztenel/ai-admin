// @ts-check
// Имя сотрудника с устройства (ТЗ v2.0 §2.5): вход в пульт — общий ключ компании, отдельных учётных записей нет, поэтому
// «кто ответил», «назначено мне» и push по сотруднику — по имени, которое сотрудник один раз вводит на своём устройстве.
// Это не защита доступа (права — по-прежнему ключ компании), а подпись в чате и журнале. Без имени — «владелец» / «администратор».
/** @param {any} v @returns {string} */
export const opName = v => String(v ?? "").replace(/[\u0000-\u001f<>]/g, "").replace(/\s+/g, " ").trim().slice(0, 32);
/** Подпись для журнала. @param {any} s сессия { role } @param {any} op */
export const opWho = (s, op) => opName(op) || (s && s.role === "owner" ? "владелец" : "администратор");
