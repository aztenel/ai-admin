// Altegio недоступен посреди диалога, у клиента уже есть запись в чате.
import { chat, showState, tag, title, check, summary, ALT, TG, days, prof, leads, env } from "./harness.mjs";
const { D1 } = days();

// ---------- A. новая просьба о записи во время сбоя, когда запись в чате уже есть
env.ALTEGIO_LOC_ALT = "3101";
title("A1. Altegio работает: Серик записан на 10:00");
let d = await chat("d1", "Серик, +7 709 222 22 33, мужская стрижка завтра в 10:00", "Записала.\n" + tag("Серик", "10:00"));
showState("d1");

title("A2. Altegio упал. Клиент просит записать ещё и сына (ИИ действует по обычным правилам 12/14: «Забронировала… [ЗАЯВКА]»)");
ALT.down = true; TG.length = 0; const leadsBefore = leads().length;
d = await chat("d1", "Запишите ещё сына Алихана на детскую стрижку завтра в 11:00",
  "Забронировала Алихана на завтра в 11:00. Администратор подтвердит запись.\n[ЗАЯВКА] Имя: Алихан; Телефон: указан; Услуга: детская стрижка; Время: завтра, 11:00");
console.log("   Telegram за это сообщение:", JSON.stringify(TG));
console.log("   новых заявок на /leads:", leads().length - leadsBefore);
check("просьба не потеряна: администратор получил заявку или уведомление про Алихана",
  leads().length > leadsBefore || TG.some(x => /Алихан/.test(x)), "заявок 0, уведомлений про Алихана 0, а клиенту сказано: «" + d.reply + "»");
showState("d1");

title("A3. то же, но ИИ отвечает «Записала вас…» (без «администратор подтвердит»)");
TG.length = 0;
d = await chat("d1", "Так запишете сына на 11:00?",
  "Записала Алихана: детская стрижка, завтра в 11:00.\n[ЗАЯВКА] Имя: Алихан; Телефон: указан; Услуга: детская стрижка; Время: завтра, 11:00");
check("клиенту не сказано «Записала», раз записи в Altegio нет", !/Записала/.test(d.reply), d.reply);
check("администратор что-то получил", TG.length > 0, "Telegram пуст");

title("A4. Altegio лежит, клиент просит отменить, ИИ пишет «Отменила вашу запись» без служебной строки");
TG.length = 0;
d = await chat("d1", "Отмените мою запись на 10:00", "Отменила вашу запись на завтра в 10:00.");
check("ложное «Отменила» не дошло до клиента", !/Отменила/.test(d.reply), d.reply);
check("администратор предупреждён об отмене", TG.some(x => /отмен/i.test(x)), "Telegram пуст: " + JSON.stringify(TG));
showState("d1");
ALT.down = false;

// ---------- B. перенос во время сбоя
env.ALTEGIO_LOC_ALT = "3102";
title("B1. Altegio работает: Марат записан на 10:00");
d = await chat("d2", "Марат, +7 705 111 22 33, мужская стрижка завтра в 10:00", "Записала.\n" + tag("Марат", "10:00"));
title("B2. Altegio упал. «Перенесите на 13:00» (ИИ по правилу 14: [ОТМЕНА] и новая бронь)");
ALT.down = true; TG.length = 0; const lb = leads().length;
d = await chat("d2", "Перенесите мою запись на 13:00",
  "Передала администратору, он подтвердит отмену. Забронировала вас на завтра в 13:00.\n[ОТМЕНА]\n[ЗАЯВКА] Имя: Марат; Телефон: указан; Услуга: мужская стрижка; Время: завтра, 13:00");
console.log("   Telegram:", JSON.stringify(TG));
console.log("   новых заявок:", leads().length - lb);
check("администратор знает, что клиент хочет на 13:00 (заявка или текст уведомления)", leads().length > lb || TG.some(x => /13:00/.test(x)));
check("клиенту сказано именно про перенос/новое время, а не только «подтвердит отмену»", /13:00|перен/i.test(d.reply), d.reply);
showState("d2");
ALT.down = false;

// ---------- C. только book_times лежит (timesDown) — тот же путь
env.ALTEGIO_LOC_ALT = "3103";
title("C1. Altegio работает: Олжас записан на 10:00");
d = await chat("d3", "Олжас, +7 705 222 22 33, мужская стрижка завтра в 10:00", "Записала.\n" + tag("Олжас", "10:00"));
title("C2. book_times отвечает 429. Клиент просит вторую запись");
ALT.timesDown = true; TG.length = 0; const lc = leads().length;
// кэш времени живёт 2 минуты в памяти изолята — сбрасываем его обращением к /altegio (страница проверки чистит кэш)
d = await chat("d3", "И ещё запишите меня на бороду послезавтра в 11:00",
  "Забронировала вас на послезавтра в 11:00. Администратор подтвердит запись.\n[ЗАЯВКА] Имя: Олжас; Телефон: указан; Услуга: оформление бороды; Время: послезавтра, 11:00");
console.log("   Telegram:", JSON.stringify(TG.map(x => x.split("\n")[0])));
console.log("   новых заявок:", leads().length - lc, "| ответ дал код или ИИ:", d.reply);
ALT.timesDown = false;
summary();
