// Время: полночь по Астане (UTC+5), записи «на сегодня», прошедшие записи.
const realNow = Date.now;
let fake = Date.UTC(2026, 9, 3, 18, 58, 0); // 23:58 3 октября по Астане
Date.now = () => fake;
const { chat, showState, tag, title, check, summary, ALT, TG, days, prof, leads, env, iso, hist } = await import("./harness.mjs");
const at = (y, m, d, hh, mm) => { fake = Date.UTC(y, m - 1, d, hh - 5, mm, 0); };

env.ALTEGIO_LOC_ALT = "4101";
ALT.dates = ["2026-10-03", "2026-10-04", "2026-10-05"];
ALT.times = { 0: ["09:30", "10:00", "11:00", "13:00", "23:59"], 11: ["10:00"], 12: ["10:00"] };

title("1. 23:58 3 октября: запись «на завтра» (4 октября) в 10:00");
let d = await chat("z1", "Тимур, +7 702 111 22 33, мужская стрижка завтра в 10:00", "Записала.\n" + tag("Тимур", "10:00", { date: "2026-10-04" }));
check("метка «завтра, воскресенье, 4 октября»", /завтра, воскресенье, 4 октября, в 10:00/.test(d.reply));

title("2. через 4 минуты, 00:02 4 октября: «я записан?» — та же запись теперь «сегодня»");
at(2026, 10, 4, 0, 2);
d = await chat("z1", "Я точно записан?", "Да, вы записаны.");
check("метка стала «сегодня, воскресенье, 4 октября»; запись на месте", /сегодня, воскресенье, 4 октября, в 10:00/.test(d.reply) && prof("z1").bookings.length === 1, d.reply);

title("3. 15:00 4 октября (время записи прошло): запись всё ещё считается активной");
at(2026, 10, 4, 15, 0);
d = await chat("z1", "Запишите ещё на завтра в 11:00", "Записала.\n" + tag("Тимур", "11:00", { date: "2026-10-05" }));
console.log("   (прошедшая сегодня запись показана как «также есть запись» и занимает место в лимите 4 на чат)");
d = await chat("z1", "Отмените запись", "Отменяю.\n[ОТМЕНА]");
check("при одной будущей и одной прошедшей записи отмена без уточнений относится к будущей (бот не переспрашивает про прошедшую)", /Отменила/.test(d.reply), d.reply);

title("4. 23:59:30 4 октября → 00:00:30 5 октября: запись на 4-е исчезает из активных");
at(2026, 10, 4, 23, 59);
d = await chat("z1", "какие у меня записи?", "Вы записаны.");
const before = prof("z1").bookings.map(b => b.date + " " + b.time);
at(2026, 10, 5, 0, 1);
d = await chat("z1", "а сейчас?", "Вы записаны.");
const after = prof("z1").bookings.map(b => b.date + " " + b.time);
console.log("   до полуночи:", JSON.stringify(before), "| после:", JSON.stringify(after));
check("после полуночи вчерашняя запись убрана, сегодняшняя осталась", after.length === 1 && after[0].startsWith("2026-10-05"));

title("5. запись на сегодня 23:59, проверка «та же запись» и отмены в 23:59");
env.ALTEGIO_LOC_ALT = "4102"; at(2026, 10, 3, 23, 30);
d = await chat("z2", "Тимур, +7 702 111 22 44, мужская стрижка сегодня в 23:59", "Записала.\n" + tag("Тимур", "23:59", { date: "2026-10-03" }));
check("метка «сегодня, суббота, 3 октября, в 23:59»", /сегодня, суббота, 3 октября, в 23:59/.test(d.reply), d.reply);
at(2026, 10, 4, 0, 0);
d = await chat("z2", "Отмените запись", "Отменяю.\n[ОТМЕНА]");
console.log("   00:00 следующего дня, отмена вчерашней записи →", d.reply);
Date.now = realNow;
summary();
