// Телефон в служебной строке [ЗАЯВКА]: worker.js:883 — opts.phone || normPhone(g("Телефон")) || saved.profile.phone
// Номер из строки ИИ важнее номера, который клиент сам написал в чате. ИИ настоящего номера не видит (он скрыт),
// поэтому любой номер в строке — это либо телефон компании из «Фактов», либо выдумка.
import { chat, showState, tag, title, check, summary, ALT, TG, days, prof, leads, env, G } from "./harness.mjs";

env.ALTEGIO_LOC_ALT = "3601";
title("A. клиент телефон НЕ давал; ИИ подставил в строку телефон компании из фактов (+7 700 000 00 40)");
let d = await chat("p1", "Запишите меня на мужскую стрижку завтра в 10:00, меня зовут Тимур",
  "Записала вас.\n" + tag("Тимур", "10:00", { phone: "+7 700 000 00 40" }));
showState("p1");
check("без телефона клиента запись не создаётся (бот просит номер)", ALT.records.length === 0, "в Altegio создана запись на номер " + (ALT.records[0] || {}).phone + "; клиенту: «" + d.reply + "»");

env.ALTEGIO_LOC_ALT = "3602"; ALT.records.length = 0;
title("B. клиент написал свой номер, а ИИ в строке указал другой (выдумал)");
d = await chat("p2", "Тимур, мой номер +7 702 111 22 33, мужская стрижка завтра в 11:00",
  "Записала вас.\n" + tag("Тимур", "11:00", { phone: "+7 705 000 00 00" }));
console.log("   что ушло в ИИ вместо номера:", JSON.stringify(G.calls.at(-1).contents.at(-1).parts[0].text));
showState("p2");
check("в Altegio ушёл номер, который написал клиент", (ALT.records[0] || {}).phone === "+77021112233", "в Altegio ушёл " + (ALT.records[0] || {}).phone);
check("в профиле чата остался номер клиента", prof("p2").phone === "+77021112233", "в профиле теперь " + prof("p2").phone);

env.ALTEGIO_LOC_ALT = "3603"; ALT.records.length = 0;
title("C. контроль: «Телефон: указан» → берётся номер клиента");
d = await chat("p3", "Тимур, мой номер +7 702 111 22 44, мужская стрижка завтра в 13:00", "Записала вас.\n" + tag("Тимур", "13:00"));
check("в Altegio ушёл номер клиента", (ALT.records[0] || {}).phone === "+77021112244");

env.ALTEGIO_LOC_ALT = "3604"; ALT.records.length = 0;
title("D. номер без кода страны (10 цифр) бот не узнаёт как телефон и отдаёт ИИ открытым текстом");
d = await chat("p4", "Тимур, 702 111 22 55, мужская стрижка завтра в 10:00", "Оставьте, пожалуйста, номер телефона.");
console.log("   что ушло в ИИ:", JSON.stringify(G.calls.at(-1).contents.at(-1).parts[0].text), "| телефон в профиле:", JSON.stringify(prof("p4").phone));
summary();
