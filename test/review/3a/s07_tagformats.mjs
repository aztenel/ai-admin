// Нестандартные служебные строки от ИИ.
import { chat, showState, tag, title, check, summary, ALT, TG, days, prof, leads, env } from "./harness.mjs";
const { D1, D2 } = days();
let loc = 3700; const next = () => { env.ALTEGIO_LOC_ALT = String(++loc); ALT.records.length = 0; ALT.deleted.length = 0; TG.length = 0; };

next(); title("1. две строки [ЗАЯВКА] в одном ответе (отец и сын)");
let d = await chat("t1", "Тимур, +7 702 100 00 01. Запишите меня на мужскую в 10:00 и сына Алихана на детскую в 11:00 завтра",
  "Записала вас обоих.\n" + tag("Тимур", "10:00") + "\n" + tag("Алихан", "11:00", { service: "Детская стрижка" }));
showState("t1");
check("обе записи созданы ИЛИ клиенту сказано, что вторая не оформлена", ALT.records.length === 2 || /Алихан|втор|11:00/.test(d.reply), "создана 1 запись; про вторую клиенту ничего не сказано: «" + d.reply + "»; уведомлений про Алихана: " + TG.filter(x => /Алихан/.test(x)).length);

next(); title("2. одна строка [ЗАЯВКА], два человека через запятую (так велит правило 12: «перечисли всех в одной строке»)");
d = await chat("t2", "Тимур, +7 702 100 00 02. Меня и сына Алихана на мужскую стрижку завтра в 10:00", "Записала.\n" + tag("Тимур, Алихан", "10:00"));
showState("t2");
console.log("   имя в записи Altegio:", JSON.stringify((ALT.records[0] || {}).fullname), "— одна запись на двоих");

next(); title("3. две строки [ОТМЕНА] (отменить обе записи)");
await chat("t3", "Тимур, +7 702 100 00 03, мужская стрижка завтра в 10:00", "Записала.\n" + tag("Тимур", "10:00"), { quiet: true });
await chat("t3", "И сына Алихана на детскую завтра в 11:00", "Записала.\n" + tag("Алихан", "11:00", { service: "Детская стрижка" }), { quiet: true });
d = await chat("t3", "Отмените обе записи", `Отменяю обе.\n[ОТМЕНА] Имя: Тимур; Дата: ${D1}; Время: 10:00\n[ОТМЕНА] Имя: Алихан; Дата: ${D1}; Время: 11:00`);
showState("t3");
check("обе отменены ИЛИ клиенту сказано, что вторая осталась", ALT.deleted.length === 2 || /остал|также|ещё|11:00/.test(d.reply), "удалена 1 из 2; клиенту: «" + d.reply + "»");
d = await chat("t3", "Обе, я же сказал", "Отменяю обе.\n[ОТМЕНА]");
console.log("   после повтора: удалено", ALT.deleted.length);

next(); title("4. [ОТМЕНА] и [ЗАЯВКА] в одной строке");
await chat("t4", "Тимур, +7 702 100 00 04, мужская стрижка завтра в 10:00", "Записала.\n" + tag("Тимур", "10:00"), { quiet: true });
d = await chat("t4", "Перенесите на 13:00", "Переношу. [ОТМЕНА] " + tag("Тимур", "13:00"));
showState("t4");
check("перенос: старая (10:00) удалена", ALT.deleted.length === 1, "старая не удалена; клиенту: «" + d.reply + "»; Telegram: " + JSON.stringify(TG.map(x => x.split("\n")[0])));

next(); title("5. время с хвостом: «Время: 9:30 утра», «Время: 09:30.», «Время: 13:00 (завтра)»");
for (const [i, tm] of ["9:30 утра", "09:30.", "13:00 (завтра)", "в 10:00", "11.00", "11:00:00"].entries()) {
  const before = ALT.records.length;
  d = await chat("t5" + i, `Тимур, +7 702 100 01 ${10 + i}, мужская стрижка завтра`, "Записала.\n" + tag("Тимур", tm), { quiet: true });
  console.log(`   «Время: ${tm}» → ${ALT.records.length > before ? "запись создана" : "НЕ создана"}; клиенту: «${d.reply.slice(0, 110)}»${d.lead && d.lead.note ? " | заявка: " + d.lead.note : ""}`);
}

next(); title("6. нет полей даты и времени: «[ЗАЯВКА] Имя: Тимур; Телефон: указан; Услуга: Мужская стрижка»");
d = await chat("t6", "Тимур, +7 702 100 00 06, мужская стрижка", "Записала вас.\n[ЗАЯВКА] Имя: Тимур; Телефон: указан; Услуга: Мужская стрижка");
console.log("   заявка:", JSON.stringify(d.lead && { time: d.lead.time, note: d.lead.note }));
check("в тексте клиенту нет пустых мест вида «, .»", !/, \.|: \.|,\s*$/.test(d.reply), d.reply);

next(); title("7. поля в другом порядке и в нижнем регистре, лишние пробелы");
d = await chat("t7", "Тимур, +7 702 100 00 07, мужская стрижка завтра в 10:00", `Записала.\n[ заявка ]   время: 10:00 ;дата:${D1};  мастер : любой; услуга: мужская стрижка; телефон: указан; имя:  Тимур `);
check("строка с пробелами внутри скобок распознана или хотя бы не показана клиенту", ALT.records.length === 1 || !/заявка \]/.test(d.reply), "клиенту показана служебная строка: «" + d.reply + "»");
d = await chat("t7b", "Тимур, +7 702 100 00 17, мужская стрижка завтра в 10:00", `Записала.\n[заявка] время: 10:00 ;дата:${D1};  мастер : любой; услуга: мужская стрижка; телефон: указан; имя:  Тимур `);
check("другой порядок полей и нижний регистр — запись создаётся", !!(d.lead && d.lead.altegio), d.reply);

next(); title("8. запятые вместо точек с запятой");
d = await chat("t8", "Тимур, +7 702 100 00 08, мужская стрижка завтра в 10:00", `Записала.\n[ЗАЯВКА] Имя: Тимур, Телефон: указан, Услуга: Мужская стрижка, Мастер: любой, Дата: ${D1}, Время: 10:00`);
console.log("   создано записей:", ALT.records.length, "| заявка:", JSON.stringify(d.lead && { name: d.lead.name, note: d.lead.note }));

next(); title("9. [ОТМЕНА] с подробностями в другом формате даты («завтра», «04.10»)");
await chat("t9", "Тимур, +7 702 100 00 09, мужская стрижка завтра в 10:00", "Записала.\n" + tag("Тимур", "10:00"), { quiet: true });
d = await chat("t9", "Отмените запись на завтра", "Отменяю.\n[ОТМЕНА] Имя: Тимур; Дата: завтра; Время: 10:00");
console.log("   удалено:", ALT.deleted.length, "| Telegram:", JSON.stringify(TG.filter(x => /❓|❌/.test(x)).map(x => x.split("\n")[0])));
check("клиенту не сказано «отменила», если ничего не удалено", ALT.deleted.length === 1 || !/Отменила/.test(d.reply), d.reply);

next(); title("10. перенос, когда новое время совпадает с уже существующей записью + [ОТМЕНА] на другую запись того же человека");
await chat("t10", "Тимур, +7 702 100 00 10, мужская стрижка завтра в 10:00", "Записала.\n" + tag("Тимур", "10:00"), { quiet: true });
await chat("t10", "И ещё послезавтра в 10:00", "Записала.\n" + tag("Тимур", "10:00", { date: D2 }), { quiet: true });
d = await chat("t10", "Завтрашнюю перенесите на 13:00", "Переношу.\n[ОТМЕНА]\n" + tag("Тимур", "13:00"));
check("бот создал новую и спросил, какую из двух старых снять", ALT.records.length === 3 && /Какую отменить/.test(d.reply));
TG.length = 0;
d = await chat("t10", "Завтрашнюю, на 10:00", `Переношу завтрашнюю запись на 13:00.\n[ОТМЕНА] Имя: Тимур; Дата: ${D1}; Время: 10:00\n` + tag("Тимур", "13:00"));
showState("t10");
check("старая запись на завтра 10:00 удалена (перенос доведён до конца)", ALT.deleted.length === 1,
  "ничего не удалено; клиенту: «" + d.reply + "»; cancel=" + d.cancel + "; Telegram: " + JSON.stringify(TG));
summary();
