// Форматы телефона и имена. Что бот распознал как телефон и что увидел ИИ.
import { chat, showState, tag, title, check, summary, ALT, TG, days, prof, leads, env, G } from "./harness.mjs";
env.ALTEGIO_LOC_ALT = "4501";
let n = 0;
title("телефон в сообщении клиента → что сохранено в профиле и что ушло в ИИ");
for (const t of [
  "Тимур, +7 (702) 111-22-33, стрижка завтра в 10:00",
  "Тимур 8-702-111-22-33 завтра 10:00",
  "Тимур 87021112233",
  "Тимур, 7 702 111 22 33",
  "Тимур, +77021112233.",
  "Тимур, 702 111 22 33",                      // без кода страны
  "Тимур +7 702 111 22 33 10:00 завтра",       // телефон, пробел, время
  "Тимур, тел. 8 702 111 22 33 2 человека",    // телефон, пробел, число
  "Тимур, +7 702 111 22 33, на 10:00",         // контроль: запятая после номера
  "My number is +1 415 555 0100, Timur",       // иностранный номер
  "Тимур, +998 90 123 45 67",                  // Узбекистан
]) {
  const sid = "f" + (++n);
  await chat(sid, t, "Спасибо! Уточните, пожалуйста, услугу.", { quiet: true });
  const seenByAI = G.calls.at(-1).contents.at(-1).parts[0].text;
  console.log(`   «${t}»\n      телефон в профиле: ${JSON.stringify(prof(sid).phone)} | ИИ увидел: «${seenByAI}»`);
}

title("имена в строке [ЗАЯВКА]: что отклоняется как «ненастоящее»");
for (const name of ["Тимур", "Ленина", "Сталина", "Путинцев Игорь", "Наполеон", "Ботагоз", "Тест", "тестовый клиент", "Еба", "Бляхер Анна", "А", "Ян", "не указано", "Клиент", "указан", "…", "-", "Иван; DROP", "<b>Иван</b>"]) {
  const sid = "g" + (++n);
  const before = ALT.records.length;
  const d = await chat(sid, "+7 702 111 22 " + String(10 + (n % 80)) + ", мужская стрижка завтра в 10:00", "Записала.\n" + tag(name, "10:00"), { quiet: true });
  console.log(`   Имя: «${name}» → ${ALT.records.length > before ? "запись создана на имя «" + ALT.records.at(-1).fullname + "»" : "НЕ создана: " + d.reply.slice(0, 60)}`);
}
