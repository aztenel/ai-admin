// Разное: тёзки с разными фамилиями, «ту, что завтра», услуга через «+», отмена одного и запись другого в одном ответе.
import { chat, showState, tag, title, check, summary, ALT, TG, days, prof, leads, env } from "./harness.mjs";
const { D1, D2 } = days();
const next = loc => { env.ALTEGIO_LOC_ALT = String(loc); ALT.records.length = 0; ALT.deleted.length = 0; TG.length = 0; };

next(4601); title("1. два тёзки с разными фамилиями в одном чате");
await chat("e1", "Тимур Ахметов, +7 702 600 00 01, мужская стрижка завтра в 10:00", "Записала.\n" + tag("Тимур Ахметов", "10:00"), { quiet: true });
let d = await chat("e1", "И моего коллегу, Тимура Иванова, на 11:00", "Записала.\n" + tag("Тимур Иванов", "11:00"));
d = await chat("e1", "Отмените запись Иванова", "Отменяю.\n[ОТМЕНА] Имя: Тимур Иванов");
check("по полному имени «Тимур Иванов» найдена одна запись", ALT.deleted.length === 1, "бот переспрашивает, причём в списке нет имён: «" + d.reply + "»");
d = await chat("e1", "Тимура Иванова, на 11:00", `Отменяю.\n[ОТМЕНА] Имя: Тимур Иванов; Дата: ${D1}; Время: 11:00`);
check("со временем — удаляется нужная", ALT.deleted.length === 1 && ALT.deleted[0].startsWith(String(ALT.records[1].id)));
title("1б. второй тёзка на то же время к другому мастеру");
d = await chat("e1", "Тогда Иванова запишите на 10:00 к Ерлану", "Записала.\n" + tag("Тимур Иванов", "10:00", { staff: "Ерлан" }));
check("запись второго человека с тем же именем на то же время создаётся", ALT.records.length === 3, d.reply);

next(4602); title("2. один человек, две записи в разные дни; «отмените ту, что завтра»");
await chat("e2", "Тимур, +7 702 600 00 02, мужская стрижка завтра в 10:00", "Записала.\n" + tag("Тимур", "10:00"), { quiet: true });
await chat("e2", "и послезавтра в 10:00 на бороду", "Записала.\n" + tag("Тимур", "10:00", { date: D2, service: "Оформление бороды" }), { quiet: true });
d = await chat("e2", "Отмените ту, что завтра", `Отменяю.\n[ОТМЕНА] Дата: ${D1}`);
check("удалена завтрашняя, послезавтрашняя цела", ALT.deleted.length === 1 && ALT.deleted[0].startsWith(String(ALT.records[0].id)) && prof("e2").bookings.length === 1 && prof("e2").bookings[0].date === D2);
d = await chat("e2", "И ту, что в 10:00", `Отменяю.\n[ОТМЕНА] Время: 10:00`);
check("по одному времени — оставшаяся запись", ALT.deleted.length === 2);

next(4603); title("3. услуги через «+» вместо « | »: «Мужская стрижка + борода»");
d = await chat("e3", "Тимур, +7 702 600 00 03, стрижка и борода завтра в 10:00", "Записала.\n" + tag("Тимур", "10:00", { service: "Мужская стрижка + борода" }));
console.log("   услуги в записи Altegio:", JSON.stringify((ALT.records[0] || {}).appointments?.[0]?.services));
check("обе услуги в записи ИЛИ бот переспросил", (ALT.records[0]?.appointments[0].services.length === 2) || ALT.records.length === 0, "создана запись только на стрижку; борода молча отброшена");
next(4604);
d = await chat("e3b", "Тимур, +7 702 600 00 13, стрижка и борода завтра в 10:00", "Записала.\n" + tag("Тимур", "10:00", { service: "Мужская стрижка | Оформление бороды" }));
check("контроль: через « | » — две услуги", ALT.records[0]?.appointments[0].services.length === 2);

next(4605); title("4. «мою отмените, а сына запишите на 11:00» — [ОТМЕНА] без подробностей + [ЗАЯВКА] на другого человека");
await chat("e4", "Тимур, +7 702 600 00 04, мужская стрижка завтра в 10:00", "Записала.\n" + tag("Тимур", "10:00"), { quiet: true });
TG.length = 0;
d = await chat("e4", "Мою запись отмените, а сына Алихана запишите на детскую в 11:00", "Сделала.\n[ОТМЕНА]\n" + tag("Алихан", "11:00", { service: "Детская стрижка" }));
showState("e4");
console.log("   Telegram:", JSON.stringify(TG.map(x => x.split("\n").join(" | ").slice(0, 200))));
check("запись Тимура отменена ИЛИ администратор получил её в уведомлении", ALT.deleted.length === 1 || TG.some(x => /❓/.test(x) && /10:00/.test(x)), "запись Тимура не отменена, а в уведомлении администратору «прежней записи нет в этом чате» — и нет ни слова о записи на 10:00");

next(4606); title("5. [ОТМЕНА] с пробелами в скобках «[ отмена ]» / латинская буква в слове");
await chat("e5", "Тимур, +7 702 600 00 05, мужская стрижка завтра в 10:00", "Записала.\n" + tag("Тимур", "10:00"), { quiet: true });
d = await chat("e5", "Отмените запись", "Отменяю.\n[ отмена ]");
check("клиенту не показана служебная строка и не сказано, что запись отменяется, если ничего не сделано", !/\[/.test(d.reply), "ответ: " + JSON.stringify(d.reply));
summary();
