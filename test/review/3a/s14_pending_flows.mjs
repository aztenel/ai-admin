// Заявка администратору вместо записи (Altegio отказал): ровно одна на просьбу; состояние pending/booked в длинном диалоге.
import { chat, showState, tag, title, check, summary, ALT, TG, days, prof, leads, env } from "./harness.mjs";
const { D1, D2 } = days();
const next = loc => { env.ALTEGIO_LOC_ALT = String(loc); ALT.records.length = 0; ALT.deleted.length = 0; TG.length = 0; };
const myLeads = phone => leads().filter(l => l.phone === phone);

next(4401); title("1. Altegio требует код из SMS; одна и та же просьба трижды");
ALT.needCode = true;
let d = await chat("q1", "Тимур, +7 702 400 00 01, мужская стрижка завтра в 11:00", "Записала.\n" + tag("Тимур", "11:00"));
d = await chat("q1", "Записали?", "Записала.\n" + tag("Тимур", "11:00"));
d = await chat("q1", "Ну что там?", "Записала вас на завтра в 11:00."); // без строки
d = await chat("q1", "Алло", "Записала.\n" + tag("Тимур Ахметов", "11:00")); // то же, имя с фамилией
check("заявка одна, уведомление одно", myLeads("+77024000001").length === 1 && TG.filter(x => /Заявка без записи/.test(x)).length === 1, `заявок ${myLeads("+77024000001").length}, уведомлений ${TG.filter(x => /Заявка без записи/.test(x)).length}`);
showState("q1");

title("1б. та же просьба, но ИИ написал время чуть иначе («11:00» → «11.00», «в 11:00»)");
const n0 = myLeads("+77024000001").length;
d = await chat("q1", "Так что с записью на 11?", "Записала.\n" + tag("Тимур", "11.00"));
d = await chat("q1", "?", "Записала.\n" + tag("Тимур", "в 11:00"));
check("повтор в другом написании не плодит заявки", myLeads("+77024000001").length === n0, `добавилось заявок: ${myLeads("+77024000001").length - n0}`);

title("1в. Altegio починили; клиент повторяет ту же просьбу");
ALT.needCode = false; TG.length = 0;
d = await chat("q1", "Попробуйте ещё раз записать на 11:00", "Записала.\n" + tag("Тимур", "11:00"));
showState("q1");
check("после починки та же просьба исполняется (а не «заявка у администратора» навсегда)", ALT.records.length === 1, "ответ: «" + d.reply + "» — запись не создана, хотя Altegio уже работает");

next(4402); title("2. отказ (500) → клиент выбрал другое время → успех. Что со старой заявкой «запишите вручную»?");
ALT.postFail = 500;
d = await chat("q2", "Марат, +7 702 400 00 02, мужская стрижка завтра в 11:00", "Записала.\n" + tag("Марат", "11:00"), { quiet: true });
ALT.postFail = 0;
d = await chat("q2", "Тогда давайте на 13:00", "Записала.\n" + tag("Марат", "13:00"));
showState("q2");
console.log("   заявки клиента на /leads:", JSON.stringify(myLeads("+77024000002").map(l => [l.time.slice(-8), l.status || "активна", l.note])));
check("старая заявка «НЕ записан — запишите вручную» помечена как неактуальная", myLeads("+77024000002").some(l => /НЕ записан/.test(l.note) && l.status), "администратор видит и «запишите вручную на 11:00», и запись на 13:00 — может записать второй раз");

next(4403); title("3. длинный диалог: запись → вторая → отмена → перенос → сбой Altegio → отмена → Altegio жив → снова запись");
d = await chat("q3", "Тимур, +7 702 400 00 03, мужская стрижка завтра в 10:00", "Записала.\n" + tag("Тимур", "10:00"), { quiet: true });
d = await chat("q3", "И сына Алихана на детскую в 11:00", "Записала.\n" + tag("Алихан", "11:00", { service: "Детская стрижка" }), { quiet: true });
d = await chat("q3", "Мою отмените", "Отменяю.\n[ОТМЕНА] Имя: Тимур", { quiet: true });
d = await chat("q3", "Сына перенесите на послезавтра 10:00", "Переношу.\n[ОТМЕНА] Имя: Алихан\n" + tag("Алихан", "10:00", { service: "Детская стрижка", date: D2 }), { quiet: true });
let p = prof("q3");
check("в чате одна запись: Алихан, послезавтра 10:00; в Altegio создано 3, удалено 2", p.bookings.length === 1 && p.bookings[0].date === D2 && ALT.records.length === 3 && ALT.deleted.length === 2 && p.pending == null);
ALT.down = true; TG.length = 0;
d = await chat("q3", "Отмените запись сына", "Передала администратору, он подтвердит отмену.\n[ОТМЕНА]");
check("сбой Altegio: клиенту «передала администратору», администратору «удалите вручную» с этой записью", /Передала администратору/.test(d.reply) && TG.some(x => /удалите вручную/.test(x) && /Алихан/.test(x) && x.includes(D2)));
ALT.down = false;
p = prof("q3");
console.log("   после сбоя запись всё ещё числится в чате:", JSON.stringify(p.bookings.map(b => b.name + " " + b.date + " " + b.time)), "| booked:", p.booked);
d = await chat("q3", "Так отменили?", "Отменяю.\n[ОТМЕНА]");
check("Altegio снова жив: отмена исполняется", d.cancelDone === true && ALT.deleted.length === 3);
d = await chat("q3", "Запишите меня завтра на 13:00", "Записала.\n" + tag("Тимур", "13:00"));
p = prof("q3"); showState("q3");
check("итог: одна запись Тимура на 13:00", p.bookings.length === 1 && p.bookings[0].time === "13:00" && p.booked.includes("13:00"));

next(4404); title("4. Altegio лежит с самого начала (записей в чате нет): клиент оставляет имя и телефон");
ALT.down = true; TG.length = 0;
d = await chat("q4", "Запишите меня завтра на 11:00, Руслан, +7 708 400 00 04", "Забронировала вас на завтра в 11:00. Администратор подтвердит запись.\n[ЗАЯВКА] Имя: Руслан; Телефон: указан; Услуга: стрижка; Время: завтра, 11:00");
check("обычная заявка администратору создана", !!d.lead && TG.some(x => /Новая заявка/.test(x)), JSON.stringify(d));
d = await chat("q4", "И жену Айгуль на 13:00", "Забронировала Айгуль на завтра в 13:00. Администратор подтвердит запись.\n[ЗАЯВКА] Имя: Айгуль; Телефон: указан; Услуга: стрижка; Время: завтра, 13:00");
check("вторая просьба в том же чате тоже доходит до администратора", !!d.lead || TG.some(x => /Айгуль/.test(x)), "клиенту: «" + d.reply + "»; заявки нет, уведомления нет");
ALT.down = false;
summary();
