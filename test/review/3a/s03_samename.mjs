// копия функций из worker.js (строки 422–424, 631–638) — чтобы показать таблицу совпадений
const clean = (s, n = 80) => String(s ?? "").replace(/\s+/g, " ").trim().slice(0, n);
const stem = name => { const w = clean(name).toLowerCase().split(" ")[0]; return w.length > 4 ? w.slice(0, -1) : w; };
const firstWord = s => clean(s).toLowerCase().split(" ")[0];
const sameName = (a, b) => { a = firstWord(a); b = firstWord(b); if (!a || !b) return false; const sa = stem(a), sb = stem(b);
  return a === b || (Math.abs(a.length - b.length) <= 2 && ((sa.length >= 4 && b.startsWith(sa)) || (sb.length >= 4 && a.startsWith(sb)))); };
title("таблица: sameName для пар разных имён");
const pairs = [["Жанар", "Жанат"], ["Самал", "Самат"], ["Данияр", "Даниял"], ["Мария", "Марина"], ["Марат", "Марал"], ["Асхат", "Асхар"], ["Айдар", "Айдана"], ["Дана", "Данат"], ["Дина", "Динара"], ["Алмас", "Алмаз"], ["Александр", "Александра"], ["Руслан", "Руслана"], ["Ринат", "Рината"], ["Бекзат", "Бекзада"], ["Алина", "Алиса"], ["Тимур", "Тимура"], ["Тимур", "Тимуру"], ["Али", "Алихан"], ["Мария", "Марии"], ["Илья", "Ильи"], ["Айгуль", "Айгуль Сериковна"]];
for (const [a, b] of pairs) console.log(`   ${a} / ${b}: ${sameName(a, b)}`);

