// The same tag decorations for a client WITH Altegio.
import { mk, D1 } from "./lib.mjs";
const h = await mk(); const log = h.quiet();
let n = 0;
for (const [name, tag] of [
  ["standard", `[ЗАЯВКА] Имя: Азамат; Телефон: указан; Услуга: Мужская стрижка; Мастер: любой; Дата: ${D1}; Время: 11:00`],
  ["colon after the tag", `[ЗАЯВКА]: Имя: Азамат; Телефон: указан; Услуга: Мужская стрижка; Мастер: любой; Дата: ${D1}; Время: 11:00`],
  ["bold tag", `**[ЗАЯВКА]** Имя: Азамат; Телефон: указан; Услуга: Мужская стрижка; Мастер: любой; Дата: ${D1}; Время: 11:00`],
  ["dash after the tag", `[ЗАЯВКА] — Имя: Азамат; Телефон: указан; Услуга: Мужская стрижка; Мастер: любой; Дата: ${D1}; Время: 11:00`],
  ["phone placeholder in brackets", `[ЗАЯВКА] Имя: Азамат; Телефон: [телефон указан]; Услуга: Мужская стрижка; Мастер: любой; Дата: ${D1}; Время: 11:00`],
  ["dots as separators", `[ЗАЯВКА] Имя: Азамат. Телефон: указан. Услуга: Мужская стрижка. Мастер: любой. Дата: ${D1}. Время: 11:00`],
  ["«Дата и время» as one key", `[ЗАЯВКА] Имя: Азамат; Телефон: указан; Услуга: Мужская стрижка; Мастер: любой; Дата и время: ${D1}, 11:00`],
]) {
  h.loc(9960 + (++n)); h.ALT.records.length = 0; h.calls.tg.length = 0;
  h.gemini = ["Записала вас: мужская стрижка, завтра в 11:00.\n" + tag];
  const d = await h.chat("alt", "d" + n, `Азамат, ${h.phone()}, мужская стрижка завтра в 11:00, мастер любой`);
  log(`${name}\n   tag  : ${tag}\n   reply: ${d.reply}\n   records in Altegio: ${h.ALT.records.length} | admin notes: ${h.calls.tg.length}`);
}
process.exit(0);
