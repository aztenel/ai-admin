// Заявки на обратный звонок (callback): свободного времени нет совсем / Altegio недоступен.
import { chat, showState, showLeads, tag, title, check, summary, ALT, TG, G, days, prof, leads, env, at, tick, mem, wa, waOn, waHist } from "./h.mjs";
const { D1, D2 } = days();
const sysOf = () => G.calls.at(-1).systemInstruction.parts[0].text;
const known = () => (sysOf().match(/Уже известно о клиенте: [^\n]*/) || ["(строки «Уже известно о клиенте» нет)"])[0];

title("A. свободного времени нет совсем: клиент оставляет имя и телефон → заявка на звонок; что попадает в профиль");
env.ALTEGIO_LOC_ALT = "3201"; ALT.loc["3201"] = { dates: [] };
let r = await chat("h1", "Хочу записаться на стрижку", "К сожалению, свободного времени на ближайшие дни нет. Оставьте имя и телефон — администратор перезвонит и подберёт время.");
check("без телефона заявки нет", !r.lead && leads().length === 0);
r = await chat("h1", "Тимур, +7 702 111 22 33", "Спасибо, Тимур! Администратор перезвонит вам в ближайшее время.");
check("заявка на звонок создана", !!r.lead && /Перезвонить клиенту/.test(r.lead.service), JSON.stringify(r.lead));
check("в заявке есть имя клиента (он его написал в этом же сообщении)", r.lead && r.lead.name !== "имя не указано", `имя в заявке: «${r.lead && r.lead.name}»`);
showState("h1");
r = await chat("h1", "А сколько стоит стрижка?", "Мужская стрижка от 6 000 ₸.");
console.log("   что теперь видит ИИ →", known());
check("в подсказке ИИ нет «имя имя не указано»", !/имя имя не указано/.test(sysOf()), known());
ALT.loc["3201"] = {}; tick(11 * 60e3); // время появилось (кэш расписания 2–10 минут истёк)
r = await chat("h1", "О, появилось время? Запишите на завтра в 10:00", "Записала.\n[ЗАЯВКА] Имя: имя не указано; Телефон: указан; Услуга: Мужская стрижка; Мастер: любой; Дата: " + D1 + "; Время: 10:00");
check("запись с именем «имя не указано» в Altegio не создаётся", !ALT.records.some(x => /не указано/.test(x.fullname)), "в Altegio: " + JSON.stringify(ALT.records.map(x => x.fullname)) + "; клиенту: " + r.reply);

title("B. Altegio недоступен; клиент пишет номер без кода страны (10 цифр) — ИИ обещает звонок");
env.ALTEGIO_LOC_ALT = "3202"; ALT.down = true;
let l0 = leads().length, tg0 = TG.length;
r = await chat("h2", "Здравствуйте, хочу на стрижку завтра", "Сейчас я не вижу расписание. Оставьте, пожалуйста, имя и номер телефона — администратор перезвонит и запишет вас.");
r = await chat("h2", "Тимур, 702 111 22 33", "Спасибо, Тимур! Администратор перезвонит вам в ближайшее время.");
check("клиенту обещан звонок → заявка или уведомление администратору есть", leads().length > l0 || TG.slice(tg0).some(t => /Перезвон|заявк/i.test(t)), `заявок ${leads().length - l0}; Telegram: ${JSON.stringify(TG.slice(tg0).map(t => t.split("\n")[0]))}; клиенту: «${r.reply}»`);
showState("h2");
title("B2. то же: свободного времени нет совсем, номер из 10 цифр");
ALT.down = false; env.ALTEGIO_LOC_ALT = "3203"; ALT.loc["3203"] = { dates: [] };
l0 = leads().length; tg0 = TG.length;
r = await chat("h3", "Тимур, 702 111 22 33, хочу стрижку", "Спасибо, Тимур! Свободного времени на ближайшие дни нет, администратор перезвонит вам и подберёт время.");
check("клиенту обещан звонок → заявка или уведомление администратору есть", leads().length > l0 || TG.slice(tg0).some(t => /Перезвон|заявк/i.test(t)), `заявок ${leads().length - l0}; Telegram: ${JSON.stringify(TG.slice(tg0).map(t => t.split("\n")[0]))}; клиенту: «${r.reply}»`);

title("C. Altegio недоступен 6 часов. Утром клиент оставил телефон (заявка на звонок). Днём пишет снова с новой просьбой");
env.ALTEGIO_LOC_ALT = "3204"; ALT.down = true; at(2026, 10, 3, 9, 0);
r = await chat("h4", "Запишите на стрижку, +7 702 111 22 55, Тимур", "Сейчас я не вижу расписание. Передам администратору, он перезвонит вам.");
check("утром заявка на звонок создана", !!r.lead);
at(2026, 10, 3, 15, 0);
l0 = leads().length; tg0 = TG.length;
r = await chat("h4", "Мне так никто и не позвонил. Запишите ещё жену на маникюр, перезвоните пожалуйста", "Приношу извинения. Передала администратору, он перезвонит вам в ближайшее время.");
const real = () => TG.slice(tg0).filter(t => !/Altegio не отвечает/.test(t));
check("днём: клиенту снова обещан звонок → администратор получил заявку или уведомление о клиенте", leads().length > l0 || real().length > 0, `новых заявок ${leads().length - l0}, уведомлений о клиенте ${real().length}; клиенту: «${r.reply}»`);
r = await chat("h4", "Запишите меня завтра на 10 утра", "Записала вас на завтра в 10:00.");
check("бот отвечает «передала вашу просьбу администратору» → администратор действительно что-то получил", (leads().length > l0 || real().length > 0), `клиенту: «${r.reply}»; новых заявок ${leads().length - l0}, уведомлений о клиенте ${real().length}`);
showLeads();
at(2026, 10, 3, 12, 0); ALT.down = false;

title("D. свободного времени нет; ИИ советует клиенту САМОМУ позвонить — заявка на звонок создаётся («позвонит» ⊂ «позвоните»)");
env.ALTEGIO_LOC_ALT = "3205"; ALT.loc["3205"] = { dates: [] };
waOn();
let w = await wa("77071112233", "Есть время на завтра?", "К сожалению, свободного времени на ближайшие дни нет. Позвоните нам, пожалуйста: +7 700 000 00 40.");
check("лишней заявки «Перезвонить клиенту» нет", !leads().some(l => l.phone === "+77071112233"), JSON.stringify(leads().filter(l => l.phone === "+77071112233").map(l => l.service)));

title("E. свободного времени нет; клиент отменяет запись и в том же сообщении пишет телефон → ответ об отмене подменяется");
env.ALTEGIO_LOC_ALT = "3206";
delete env.WA_CLIENT;
await chat("h6", "Тимур, +7 702 111 22 66, стрижка завтра в 10:00", "Записала.\n" + tag("Тимур", "10:00"), { quiet: true });
ALT.loc["3206"] = { dates: [] }; tick(11 * 60e3); // расписание опустело (кэш 2–10 минут истёк)
r = await chat("h6", "Отмените мою запись, если что мой номер +7 702 111 22 66", "Отменяю.\n[ОТМЕНА]");
check("клиенту сказано, что запись отменена", /Отменила вашу запись/.test(r.reply), r.reply + ` | cancel=${r.cancel} cancelDone=${r.cancelDone} lead=${r.lead && r.lead.service}`);
summary();
