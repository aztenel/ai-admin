// Заявка на обратный звонок зависит от слов ИИ: /перезвон|свяж[еу]тся|позвонит|call back|хабарлас/. Другие обычные формулировки заявку не создают.
// WhatsApp: телефон известен всегда, но «в тексте сообщения» его нет — значит, всё решает формулировка ИИ.
import { title, check, summary, ALT, TG, G, days, leads, env, at, tick, mem, wa, waOn, LOG } from "./h.mjs";
waOn("alt");
LOG.quiet = true;
const PHR = [
  "Сейчас я не вижу расписание. Администратор перезвонит вам.",                       // контроль: слово из списка
  "Сейчас я не вижу расписание. Мы свяжемся с вами в ближайшее время.",
  "Сейчас я не вижу расписание. Вам позвонят и подберут время.",
  "Сейчас я не вижу расписание. Передам вашу просьбу администратору.",
  "Сейчас я не вижу расписание. Администратор напишет вам в этот чат.",
  "Сейчас я не вижу расписание. Администратор наберёт вас в течение часа.",
  "Сейчас записать не получится, ваш запрос передан администратору.",
  "I can't see the schedule right now. We will contact you shortly.",
  "Қазір кестені көре алмай тұрмын. Әкімші сізге қоңырау шалады.",
];
let n = 0;
for (const mode of ["Altegio недоступен", "свободного времени нет совсем"]) {
  title(mode + ": клиент WhatsApp просит записать; что обещает ИИ → создана ли заявка администратору");
  for (const p of PHR) {
    const from = "7707222" + String(1000 + (++n)), loc = String(4400 + n);
    env.ALTEGIO_LOC_ALT = loc;
    if (mode === "Altegio недоступен") ALT.down = true; else { ALT.down = false; ALT.loc[loc] = { dates: [] }; }
    const l0 = leads().length, t0 = TG.length;
    await wa(from, "Здравствуйте", "Здравствуйте! Чем помочь?");
    const w = await wa(from, "Запишите меня на стрижку завтра утром, меня зовут Тимур", p);
    const got = leads().length > l0 || TG.slice(t0).some(t => !/Altegio не отвечает/.test(t));
    check(`ИИ: «${p}» → ${got ? "заявка создана" : "заявки НЕТ, администратор ничего не получил"}`, got);
  }
}
ALT.down = false;
summary();
