// Заявки администратору: потолок adminLeads, пометка «заменена», pend (ключ, срок, 5 штук), «maybe».
import { chat, showState, showLeads, tag, title, check, summary, ALT, TG, days, prof, leads, env, at, tick, T, mem, wa, waOn, waHist, altReset } from "./h.mjs";
const { D1, D2 } = days();

title("A. потолок 6 заявок на чат не сбрасывается никогда: 6 отказов в субботу → новая просьба через 5 дней теряется");
env.ALTEGIO_LOC_ALT = "3101";
ALT.needCode = true; // локация требует код из SMS → каждая запись = заявка администратору (не «maybe»)
const times = ["9:30", "10:00", "11:00", "13:00", "15:00", "16:00"];
let r;
for (const t of times) r = await chat("g1", `Тимур, +7 702 111 22 33, стрижка завтра в ${t}`, "Записала.\n" + tag("Тимур", t), { quiet: true });
console.log("   после 6 просьб: заявок на /leads =", leads().length, "| adminLeads =", prof("g1").adminLeads, "| последний ответ:", r.reply);
ALT.needCode = false;
at(2026, 10, 8, 12, 0); // прошло 5 дней, Altegio давно работает, но у этой локации, допустим, превышен суточный лимит → нужна заявка администратору
const d = days();
mem.set(`bk:3101:all:${d.D0}`, "60");
const tg0 = TG.length, l0 = leads().length;
r = await chat("g1", "Здравствуйте, запишите меня на завтра в 10:00, Тимур", "Записала.\n" + tag("Тимур", "10:00", { date: d.D1 }));
check("новая заявка через 5 дней создана и дошла до администратора", leads().length === l0 + 1 && TG.length > tg0, `заявок добавилось ${leads().length - l0}, уведомлений ${TG.length - tg0}; клиенту: «${r.reply}»`);
showState("g1");
at(2026, 10, 3, 12, 0);

title("B. «заменена»: заявка без записи на ДРУГУЮ услугу и день помечается ненужной после любой удачной записи того же человека");
env.ALTEGIO_LOC_ALT = "3102";
ALT.loc["3102"] = { services: Array.from({ length: 160 }, (_, i) => ({ id: 1000 + i, title: i === 0 ? "Мужская стрижка" : "Услуга " + i, category_id: 1, price_min: 1000, price_max: 1000, active: 1, seance_length: 1800 })) };
r = await chat("g2", "Тимур, +7 702 111 22 44. Окрашивание бороды послезавтра в 11:00", "Записала.\n" + tag("Тимур", "11:00", { service: "Окрашивание бороды", date: D2 }));
console.log("   (услуги нет в части списка, которую видит бот → заявка администратору)");
showLeads();
r = await chat("g2", "И ещё стрижку завтра в 10:00", "Записала.\n" + tag("Тимур", "10:00", { service: "Мужская стрижка" }));
showLeads();
const first = leads().find(l => /Окрашивание/.test(l.service));
check("заявка на окрашивание (другая услуга, другой день) осталась активной", !first.status, `статус «${first.status}», пометка: «${first.note}»; Telegram: ${JSON.stringify(r.tg.filter(t => /больше не нужна/.test(t)))}`);

title("C. заявка «возможно, записан» (maybe) не помечается — как задумано");
env.ALTEGIO_LOC_ALT = "3103";
ALT.postFail = 500;
r = await chat("g3", "Тимур, +7 702 111 22 55, стрижка завтра в 11:00", "Записала.\n" + tag("Тимур", "11:00"), { quiet: true });
ALT.postFail = 0;
r = await chat("g3", "Давайте тогда в 13:00", "Записала.\n" + tag("Тимур", "13:00"), { quiet: true });
showLeads();
check("maybe-заявка осталась активной", !leads().find(l => /ВОЗМОЖНО/.test(l.note || "")).status);

title("D. pend: та же просьба в другом написании даты и времени не плодит заявки");
env.ALTEGIO_LOC_ALT = "3104";
ALT.needCode = true;
const l1 = leads().length;
await chat("g4", "Тимур, +7 702 111 22 66, стрижка завтра в 11:00", "Записала.\n" + tag("Тимур", "11:00"), { quiet: true });
for (const v of [`[ЗАЯВКА] Имя: Тимур; Телефон: указан; Услуга: Мужская стрижка; Мастер: любой; Дата: завтра; Время: 11.00`,
  `[ЗАЯВКА] Имя: Тимур; Телефон: указан; Услуга: Мужская стрижка; Мастер: любой; Дата: 04.10; Время: в 11:00`,
  `[ЗАЯВКА] Имя: тимур; Телефон: указан; Услуга: Мужская стрижка; Мастер: любой; Дата: 4 октября; Время: 11:00:00`,
  `[ЗАЯВКА] Имя: Тимур Ахметов; Телефон: указан; Услуга: Мужская стрижка; Мастер: любой; Дата: ${D1}; Время: 11:00`])
  r = await chat("g4", "Ну что, записали?", "Записала.\n" + v, { quiet: true });
check("заявка одна", leads().length === l1 + 1, `добавилось ${leads().length - l1}; ответ: ${r.reply}`);
ALT.needCode = false;

title("E. pend: больше 5 заявок — самая старая выпадает, и повтор самой первой просьбы создаёт новую заявку (до потолка 6)");
env.ALTEGIO_LOC_ALT = "3105";
ALT.needCode = true;
const l2 = leads().length;
for (const t of times) await chat("g5", `Тимур, +7 702 111 22 77, стрижка завтра в ${t}`, "Записала.\n" + tag("Тимур", t), { quiet: true });
console.log("   заявок:", leads().length - l2, "| pend:", JSON.stringify(prof("g5").pend.map(p => p.key)), "| adminLeads:", prof("g5").adminLeads);
r = await chat("g5", "Так на 9:30 записали?", "Записала.\n" + tag("Тимур", "9:30"));
console.log("   (ключа 9:30 в pend уже нет, а потолок 6 достигнут → «adminBusy»)");
ALT.needCode = false;

title("F. pend с датой, которую бот не разобрал: заявка «висит» без срока и глушит похожие просьбы");
env.ALTEGIO_LOC_ALT = "3106";
r = await chat("g6", "Тимур, +7 702 111 22 88, стрижка в субботу утром", "Записала.\n[ЗАЯВКА] Имя: Тимур; Телефон: указан; Услуга: Мужская стрижка; Мастер: любой; Дата: суббота; Время: утром");
showState("g6");
at(2026, 10, 8, 12, 0); // через 5 дней (история чата живёт 7 дней после последнего сообщения)
const l3 = leads().length;
r = await chat("g6", "Запишите меня снова в субботу утром", "Записала.\n[ЗАЯВКА] Имя: Тимур; Телефон: указан; Услуга: Мужская стрижка; Мастер: любой; Дата: суббота; Время: утром");
check("через 5 дней такая же по форме просьба («суббота, утром» — уже другая суббота) — это новая заявка", leads().length === l3 + 1, `новых заявок ${leads().length - l3}; клиенту: «${r.reply}»`);
at(2026, 10, 3, 12, 0);
summary();
