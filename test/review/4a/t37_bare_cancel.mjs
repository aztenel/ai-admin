// «Голая» строка [ОТМЕНА] (без имени, дня и времени), когда клиент просит отменить НЕ ту запись, что есть в чате.
// Правило Е в подсказке велит ИИ ставить голую [ОТМЕНА], если запись в чате одна.
import { chat, showState, tag, title, check, summary, ALT, TG, days, prof, leads, env } from "./h.mjs";
const { D1, D2 } = days();
const live = loc => ALT.records.filter(x => x.loc === loc && !x.deleted).map(x => `${x.fullname} ${x.appointments[0].datetime.slice(5, 16)}`);

title("1. в чате запись Тимура на завтра 10:00; клиент: «Отмените запись моей жены Айгуль на завтра в 15:00» (её записывали по телефону); ИИ: голая [ОТМЕНА]");
env.ALTEGIO_LOC_ALT = "4301";
await chat("v1", "Тимур, +7 702 111 22 33, завтра 10:00", "Записала.\n" + tag("Тимур", "10:00"), { quiet: true });
let r = await chat("v1", "Отмените запись моей жены Айгуль на завтра в 15:00", "Отменяю запись.\n[ОТМЕНА]");
check("запись Тимура на 10:00 цела (клиент называл другое имя и другое время)", live("4301").length === 1, `живые записи: ${JSON.stringify(live("4301"))}; клиенту: «${r.reply}»`);

title("2. в чате запись на завтра 10:00; клиент: «Отмените мою запись на послезавтра» (другая, сделана по телефону); ИИ: голая [ОТМЕНА]");
env.ALTEGIO_LOC_ALT = "4302";
await chat("v2", "Тимур, +7 702 111 22 44, завтра 10:00", "Записала.\n" + tag("Тимур", "10:00"), { quiet: true });
r = await chat("v2", "Отмените мою запись на послезавтра в 16:00", "Отменяю.\n[ОТМЕНА]");
check("запись на завтра 10:00 цела", live("4302").length === 1, `живые записи: ${JSON.stringify(live("4302"))}; клиенту: «${r.reply}»`);

title("3. контроль: клиент называет ту самую запись → отмена выполняется");
env.ALTEGIO_LOC_ALT = "4303";
await chat("v3", "Тимур, +7 702 111 22 55, завтра 10:00", "Записала.\n" + tag("Тимур", "10:00"), { quiet: true });
r = await chat("v3", "Отмените мою запись на завтра в 10:00", "Отменяю.\n[ОТМЕНА]");
check("запись удалена", live("4303").length === 0, r.reply);
summary();
