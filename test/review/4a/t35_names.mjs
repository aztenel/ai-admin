// Имена: отмена и повтор записи по имени — похожие имена, фамилии, казахское и русское написание, падежи.
import { chat, showState, tag, title, check, summary, ALT, TG, G, days, prof, leads, env, mem, LOG } from "./h.mjs";
const { D0, D1, D2 } = days();
LOG.quiet = true;
let loc = 4200, n = 0;
const live = l => ALT.records.filter(x => x.loc === String(l) && !x.deleted).map(x => x.fullname);
const fresh = () => { env.ALTEGIO_LOC_ALT = String(++loc); for (const k of [...mem.keys()]) if (k.startsWith("bk:")) mem.delete(k); return "nm" + (++n); };

title("A. в чате ОДНА запись (на имя X); строка отмены «[ОТМЕНА] Имя: Y» без дня и времени. Удалена ли запись X?");
const A = [
  // [X в чате, Y в строке отмены, должна ли запись X быть удалена]
  ["Тимур", "Тимур", true], ["Тимур", "тимур", true], ["Тимур Ахметов", "Тимур", true], ["Тимур", "Тимур Ахметов", true], ["Тимур Ахметов", "Тимур Иванов", false], ["Тимур Ахметов", "Ахметов Тимур", true],
  ["Жанар", "Жанат", false], ["Али", "Алихан", false], ["Алихан", "Али", false], ["Алия", "Али", false], ["Данияр", "Даниял", false], ["Тимур", "Тим", false],
  ["Айгүл", "Айгуль", true], ["Нұрлан", "Нурлан", true], ["Әлия", "Алия", true], ["Timur", "Тимур", true], ["Пётр", "Петр", true],
  ["Тимур", "Тимура", false /* как задумано: падеж только вместе с днём или временем */], ["Тимур", "Тимур.", true], ["Тимур", "«Тимур»", true], ["Тимур", "Тимур (я)", true], ["Алихан", "сына Алихана", false], ["Алихан", "Алихан (сын)", true],
];
for (const [x, y, want] of A) {
  const sid = fresh();
  await chat(sid, `${x}, +7 702 111 22 33, завтра 10:00`, "Записала.\n" + tag(x, "10:00"));
  const r = await chat(sid, "Отмените запись", "Отменяю.\n[ОТМЕНА] Имя: " + y);
  const gone = live(loc).length === 0;
  check(`запись «${x}», отмена «${y}» → ${gone ? "УДАЛЕНА" : "не удалена (" + (r.reply.slice(0, 46)) + "…)"}`, gone === want, `ожидалось: ${want ? "удалить" : "не удалять"}`);
}

title("B. то же, но в строке отмены есть день и время записи: «[ОТМЕНА] Имя: Y; Дата: …; Время: 10:00»");
const B = [["Тимур", "Тимура", true], ["Тимур", "Тимуру", true], ["Мария", "Марии", true], ["Айгуль", "Айгули", true], ["Арман", "Арманның", true], ["Александр", "Александра", false], ["Жанар", "Жанат", false], ["Тимур", "Тимур.", true], ["Алихан", "сына Алихана", true]];
for (const [x, y, want] of B) {
  const sid = fresh();
  await chat(sid, `${x}, +7 702 111 22 33, завтра 10:00`, "Записала.\n" + tag(x, "10:00"));
  const r = await chat(sid, "Отмените запись", `Отменяю.\n[ОТМЕНА] Имя: ${y}; Дата: ${D1}; Время: 10:00`);
  const gone = live(loc).length === 0;
  check(`запись «${x}», отмена «${y}» + день и время → ${gone ? "УДАЛЕНА" : "не удалена (" + (r.reply.slice(0, 46)) + "…)"}`, gone === want, `ожидалось: ${want ? "удалить" : "не удалять"}`);
}

title("C. в чате ДВЕ записи на одно время к разным мастерам: X (Арман, 10:00) и Y (Ерлан, 10:00); отмена «Имя: X» → удалена только X");
const C = [["Жанар", "Жанат"], ["Али", "Алихан"], ["Тимур Ахметов", "Тимур Иванов"], ["Тимур", "Тимур Ахметов"], ["Александр", "Александра"], ["Айгүл", "Айгуль"]];
for (const [x, y] of C) {
  const sid = fresh();
  const r0 = await chat(sid, `двое, +7 702 111 22 33`, "Записала.\n" + tag(x, "10:00", { staff: "Арман" }) + "\n" + tag(y, "10:00", { staff: "Ерлан" }));
  const made = live(loc).slice();
  const r = await chat(sid, "Отмените запись", "Отменяю.\n[ОТМЕНА] Имя: " + x);
  const left = live(loc);
  check(`«${x}» и «${y}»: создано ${JSON.stringify(made)}, после отмены «${x}» осталось ${JSON.stringify(left)}`, made.length === 2 && left.length === 1 && left[0] === y, `ответ на запись: ${r0.reply.slice(0, 120)} | ответ на отмену: ${r.reply.slice(0, 120)}`);
}

title("D. повтор строки [ЗАЯВКА] на то же время с ДРУГИМ написанием того же имени → второй записи быть не должно");
const D = [["Тимур", "Тимур Ахметов"], ["Айгүл", "Айгуль"], ["Нұрлан", "Нурлан"], ["Timur", "Тимур"], ["Тимур Ахметов", "Ахметов Тимур"], ["Тимур", "Тимур."]];
for (const [x, y] of D) {
  const sid = fresh();
  await chat(sid, `${x}, +7 702 111 22 33, завтра 10:00`, "Записала.\n" + tag(x, "10:00"));
  const r = await chat(sid, "Я точно записан?", "Да.\n" + tag(y, "10:00"));
  check(`«${x}» → повтор как «${y}»: записей ${live(loc).length}`, live(loc).length === 1, r.reply.slice(0, 140));
}
summary();
