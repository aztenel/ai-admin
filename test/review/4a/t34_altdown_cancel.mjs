// Altegio недоступен: отмена, когда последняя заявка чата — заявка на звонок или заявка администратору.
import { chat, showState, showLeads, tag, title, check, summary, ALT, TG, G, days, prof, hist, leads, env, at, tick, mem } from "./h.mjs";
const { D0, D1, D2 } = days();

title("1. Altegio недоступен. Клиент (записан по телефону) оставил номер → заявка на звонок. Потом просит отменить свою запись");
env.ALTEGIO_LOC_ALT = "4101"; ALT.down = true;
let r = await chat("u1", "Здравствуйте, мой номер +7 702 111 22 33, перезвоните", "Сейчас я не вижу расписание. Администратор перезвонит вам.");
check("заявка на звонок создана", !!r.lead);
r = await chat("u1", "Вообще я хотел отменить свою запись на завтра в 10:00, я Марат", "Передала администратору, он подтвердит отмену.\n[ОТМЕНА]");
showLeads();
const cb = leads().find(l => /Перезвонить/.test(l.service));
check("заявка на звонок осталась активной (клиенту всё ещё надо перезвонить)", !cb.status, `статус заявки на звонок: «${cb.status}»`);
check("администратор получил просьбу об отмене с телефоном и словами клиента", r.tg.some(t => /\+77021112233/.test(t) && /завтра в 10:00/.test(t)), JSON.stringify(r.tg));

title("2. Altegio недоступен. Заявка «запишите вручную» создана; клиент передумал: «отмените заявку»; потом снова просит то же время");
env.ALTEGIO_LOC_ALT = "4102";
r = await chat("u2", "Тимур, +7 702 111 22 44, стрижка завтра в 11:00", "Забронировала.\n[ЗАЯВКА] Имя: Тимур; Телефон: указан; Услуга: мужская стрижка; Время: завтра, 11:00");
r = await chat("u2", "Отмените, я передумал", "Передала администратору, он подтвердит отмену.\n[ОТМЕНА]");
showLeads(); showState("u2");
const l0 = leads().length;
r = await chat("u2", "Нет, всё-таки запишите на завтра в 11:00", "Забронировала.\n[ЗАЯВКА] Имя: Тимур; Телефон: указан; Услуга: мужская стрижка; Время: завтра, 11:00");
check("после отмены заявки повторная просьба — это новая заявка (старая помечена «отменена»)", leads().length === l0 + 1, `новых заявок ${leads().length - l0}; клиенту: «${r.reply}»`);
ALT.down = false;

title("3. то же при работающем Altegio: заявка администратору (код из SMS) → клиент отменяет → просит снова");
env.ALTEGIO_LOC_ALT = "4103"; ALT.needCode = true;
r = await chat("u3", "Тимур, +7 702 111 22 55, стрижка завтра в 11:00", "Записала.\n" + tag("Тимур", "11:00"));
r = await chat("u3", "Отмените, я передумал", "Отменяю.\n[ОТМЕНА]");
console.log("   администратору:", JSON.stringify(r.tg.map(t => t.split("\n")[0])));
showLeads(); showState("u3");
check("заявка «запишите вручную» помечена отменённой или администратор понял, что отменять надо её", leads().some(l => l.phone === "+77021112255" && l.status === "отменена") || r.tg.some(t => /заявк/i.test(t)), JSON.stringify(leads().filter(l => l.phone === "+77021112255").map(l => l.status || "активна")) + " | " + JSON.stringify(r.tg));
ALT.needCode = false;
summary();
