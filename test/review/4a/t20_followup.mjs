// Клиент переспрашивает после УСПЕШНОГО действия, а ИИ повторяет те же служебные строки или подтверждает словами.
import { chat, showState, showLeads, tag, title, check, summary, ALT, TG, days, prof, leads, env } from "./h.mjs";
const { D1 } = days();
const adm = r => (r.tg || []).filter(t => !/^✅ Новая запись|^❌ Отмена:/.test(t));

title("A. перенос выполнен; клиент: «Так перенесли?»; ИИ повторяет [ОТМЕНА] + [ЗАЯВКА] на то же новое время");
env.ALTEGIO_LOC_ALT = "3001";
await chat("f1", "Марат, +7 705 111 22 33, мужская стрижка завтра в 10:00", "Записала.\n" + tag("Марат", "10:00"), { quiet: true });
let r = await chat("f1", "Перенесите на 13:00", "Переношу.\n[ОТМЕНА]\n" + tag("Марат", "13:00"));
check("перенос выполнен", /Перенесла вашу запись/.test(r.reply) && ALT.deleted.length === 1);
r = await chat("f1", "Так перенесли?", "Да, перенесла вашу запись на 13:00.\n[ОТМЕНА]\n" + tag("Марат", "13:00"));
check("клиенту не говорят «Прежнюю запись отменит администратор» (она уже удалена ботом)", !/отменит администратор/.test(r.reply), r.reply);
check("администратору не уходит «отмените её вручную»", adm(r).length === 0, JSON.stringify(adm(r)));
check("cancel=false (ничего не отменялось)", !r.cancel, `cancel=${r.cancel} cancelDone=${r.cancelDone}`);
showState("f1");

title("B. отмена выполнена; клиент: «Точно отменили?»; ИИ: «Да, ваша запись отменена.» (без строки)");
env.ALTEGIO_LOC_ALT = "3002";
await chat("f2", "Тимур, +7 702 111 22 33, мужская стрижка завтра в 10:00", "Записала.\n" + tag("Тимур", "10:00"), { quiet: true });
r = await chat("f2", "Отмените запись", "Отменяю.\n[ОТМЕНА]");
check("отмена выполнена", /Отменила вашу запись/.test(r.reply) && r.cancelDone === true);
r = await chat("f2", "Точно отменили?", "Да, ваша запись на завтра в 10:00 отменена.");
check("клиенту не говорят «Передала администратору, он подтвердит отмену» про уже удалённую запись", !/Передала администратору/.test(r.reply), r.reply);
check("администратору не уходит «просит отменить запись, которой нет в этом чате»", adm(r).length === 0, JSON.stringify(adm(r)));

title("B2. то же, но ИИ повторяет строку [ОТМЕНА]");
env.ALTEGIO_LOC_ALT = "3003";
await chat("f3", "Тимур, +7 702 111 22 44, мужская стрижка завтра в 10:00", "Записала.\n" + tag("Тимур", "10:00"), { quiet: true });
await chat("f3", "Отмените запись", "Отменяю.\n[ОТМЕНА]", { quiet: true });
r = await chat("f3", "Отменили?", "Да, запись отменена.\n[ОТМЕНА]");
check("клиенту не говорят «Передала администратору, он подтвердит отмену»", !/Передала администратору/.test(r.reply), r.reply);
check("администратору не уходит лишнее уведомление", adm(r).length === 0, JSON.stringify(adm(r)));

title("C. запись создана; клиент: «Я точно записан?»; ИИ повторяет [ЗАЯВКА]");
env.ALTEGIO_LOC_ALT = "3004";
await chat("f4", "Тимур, +7 702 111 22 55, мужская стрижка завтра в 10:00", "Записала.\n" + tag("Тимур", "10:00"), { quiet: true });
const n0 = ALT.records.length;
r = await chat("f4", "Я точно записан?", "Да, вы записаны на завтра в 10:00.\n" + tag("Тимур", "10:00"));
check("второй записи нет, клиенту «Вы уже записаны»", ALT.records.length === n0 && /Вы уже записаны|у вас есть запись/i.test(r.reply), r.reply);

title("D. одна запись, ИИ дал ДВЕ строки [ОТМЕНА] (в тексте и в конце)");
env.ALTEGIO_LOC_ALT = "3005";
await chat("f5", "Тимур, +7 702 111 22 66, мужская стрижка завтра в 10:00", "Записала.\n" + tag("Тимур", "10:00"), { quiet: true });
r = await chat("f5", "Отмените запись", "Отменяю вашу запись.\n[ОТМЕНА]\nЕсли захотите — запишу снова.\n[ОТМЕНА]");
check("одна отмена, без «Передала администратору»", /Отменила вашу запись/.test(r.reply) && !/Передала администратору/.test(r.reply), r.reply);
check("cancelDone=true", r.cancelDone === true, `cancel=${r.cancel} cancelDone=${r.cancelDone}`);
check("администратору одно уведомление об отмене, без «которой нет в этом чате»", adm(r).length === 0, JSON.stringify(adm(r)));

title("E. ИИ дал ДВЕ одинаковые строки [ЗАЯВКА]");
env.ALTEGIO_LOC_ALT = "3006";
r = await chat("f6", "Тимур, +7 702 111 22 77, мужская стрижка завтра в 10:00", "Записала.\n" + tag("Тимур", "10:00") + "\n" + tag("Тимур", "10:00"));
check("в ответе нет «Вы уже записаны» сразу после «Записала вас» про ту же запись", !/Вы уже записаны/.test(r.reply), r.reply);

title("F. после отмены в ответе кнопка с только что отменённым временем");
env.ALTEGIO_LOC_ALT = "3007";
await chat("f7", "Тимур, +7 702 111 22 88, мужская стрижка завтра в 13:00", "Записала.\n" + tag("Тимур", "13:00"), { quiet: true });
r = await chat("f7", "Отмените запись", "Отменяю.\n[ОТМЕНА]");
check("после «Отменила…» нет кнопок времени", !(r.offer || []).length, "offer=" + JSON.stringify(r.offer));
summary();
