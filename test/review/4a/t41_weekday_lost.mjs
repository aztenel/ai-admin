// День недели в поле «Время» (так ИИ пишет по обычному правилу 12: «Время: день и время») теряется в заявке администратору.
import { chat, showLeads, tag, title, check, summary, ALT, TG, days, leads, env } from "./h.mjs";
const { D1 } = days();

title("1. Altegio недоступен: «[ЗАЯВКА] …; Время: суббота, 11:00»");
env.ALTEGIO_LOC_ALT = "4601"; ALT.down = true;
let r = await chat("w1", "Тимур, +7 702 111 22 33, запишите на стрижку в следующую субботу на 11", "Забронировала вас на субботу в 11:00. Администратор подтвердит запись.\n[ЗАЯВКА] Имя: Тимур; Телефон: указан; Услуга: стрижка; Время: в субботу, 11:00");
check("в заявке и в ответе клиенту есть день («суббота»)", /суббот/.test(r.reply) && /суббот/.test((r.lead || {}).time || ""), `клиенту: «${r.reply}»; время в заявке: «${(r.lead || {}).time}»; Telegram: ${JSON.stringify(r.tg.filter(t => /Заявка/.test(t)))}`);
ALT.down = false;

title("2. Altegio работает, ИИ не указал «Дата», а день недели написал в «Время»");
env.ALTEGIO_LOC_ALT = "4602";
r = await chat("w2", "Тимур, +7 702 111 22 44, запишите на стрижку в следующую субботу на 11", "Записала.\n[ЗАЯВКА] Имя: Тимур; Телефон: указан; Услуга: Мужская стрижка; Мастер: любой; Время: в субботу, 11:00");
check("в заявке и в ответе клиенту есть день («суббота»)", /суббот/.test(r.reply) && /суббот/.test((r.lead || {}).time || ""), `клиенту: «${r.reply}»; время в заявке: «${(r.lead || {}).time}»`);

title("3. Altegio недоступен; в чате уже есть запись Тимура на завтра 10:00; ИИ повторил строку [ЗАЯВКА] на неё же («я точно записан?»)");
env.ALTEGIO_LOC_ALT = "4603";
await chat("w3", "Тимур, +7 702 111 22 55, завтра 10:00", "Записала.\n" + tag("Тимур", "10:00"), { quiet: true });
ALT.down = true; env.ALTEGIO_LOC_ALT = "4603"; (await import("./h.mjs")).tick(11 * 60e3);
const l0 = leads().length;
r = await chat("w3", "Я точно записан?", "Да, вы записаны на завтра в 10:00.\n[ЗАЯВКА] Имя: Тимур; Телефон: указан; Услуга: мужская стрижка; Время: завтра, 10:00");
check("лишней заявки «НЕ записан — запишите вручную» на уже существующую запись нет", leads().length === l0, `новых заявок ${leads().length - l0}; клиенту: «${r.reply}»; Telegram: ${JSON.stringify(r.tg.map(t => t.split("\n").slice(0, 1).concat(t.split("\n").slice(-1)).join(" … ")))}`);
ALT.down = false;
summary();
